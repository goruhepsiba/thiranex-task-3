import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error

print("Libraries imported successfully!")

from google.colab import files

uploaded = files.upload()

import pandas as pd

file_name = list(uploaded.keys())[0]

df = pd.read_csv(file_name)

print("Dataset uploaded successfully!")

df.head()

print("Dataset Shape:", df.shape)

print("\nColumn Names:")
print(df.columns)

print("\nDataset Information:")
df.info()

print("\nMissing Values:")
print(df.isnull().sum())

df['Order Date'] = pd.to_datetime(
    df['Order Date'], errors='coerce'
)

df['Sales'] = pd.to_numeric(
    df['Sales'], errors='coerce'
)

df = df.dropna(subset=['Order Date', 'Sales'])

df = df.sort_values('Order Date')

print("Data cleaning completed!")

monthly_sales = (
    df.set_index('Order Date')['Sales']
    .resample('MS')
    .sum()
)

print(monthly_sales)

plt.figure(figsize=(12,5))

plt.plot(monthly_sales.index,
         monthly_sales.values,
         marker='o')

plt.title("Historical Monthly Sales")
plt.xlabel("Month")
plt.ylabel("Total Sales")

plt.grid(True)
plt.show()

data = monthly_sales.reset_index()

data.columns = ['Date', 'Sales']

data['Time'] = np.arange(len(data))

X = data[['Time']]
y = data['Sales']

split = int(len(data) * 0.8)

X_train = X.iloc[:split]
X_test = X.iloc[split:]

y_train = y.iloc[:split]
y_test = y.iloc[split:]

model = LinearRegression()

model.fit(X_train, y_train)

print("Model training completed!")

predictions = model.predict(X_test)

mae = mean_absolute_error(y_test, predictions)

rmse = np.sqrt(mean_squared_error(
    y_test, predictions
))

nonzero = y_test != 0

mape = np.mean(
    np.abs(
        (y_test[nonzero] - predictions[nonzero])
        / y_test[nonzero]
    )
) * 100

print("MAE:", mae)
print("RMSE:", rmse)
print("MAPE:", mape, "%")

plt.figure(figsize=(12,5))

plt.plot(data['Date'].iloc[split:],
         y_test,
         label='Actual Sales',
         marker='o')

plt.plot(data['Date'].iloc[split:],
         predictions,
         label='Predicted Sales',
         marker='o')

plt.title("Actual vs Predicted Sales")
plt.xlabel("Date")
plt.ylabel("Sales")

plt.legend()
plt.grid(True)
plt.show()

future_periods = 6

future_time = np.arange(
    len(data),
    len(data) + future_periods
)

future_X = pd.DataFrame({
    'Time': future_time
})

future_predictions = model.predict(future_X)

future_dates = pd.date_range(
    start=data['Date'].max() + pd.offsets.MonthBegin(1),
    periods=future_periods,
    freq='MS'
)

forecast = pd.DataFrame({
    'Month': future_dates,
    'Predicted Sales': future_predictions
})

print(forecast)

plt.figure(figsize=(12,5))

plt.plot(data['Date'],
         data['Sales'],
         label='Historical Sales')

plt.plot(future_dates,
         future_predictions,
         label='Future Predictions',
         marker='o')

plt.title("Future Sales Forecast")

plt.xlabel("Date")
plt.ylabel("Sales")

plt.legend()
plt.grid(True)
plt.show()